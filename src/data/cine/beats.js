// 第 n 拍（從 0 算，可以有小數＝拍子之間）在過場裡的秒數；off＝劇本的配樂從曲子的第幾秒開始、at＝配樂在過場的第幾秒進來
export function beatAt(track, n, off = 0, at = 0) {
  const B = BEATS[track];
  if (!B) return at + n * 0.5;
  const b = B.beats.filter((t) => t >= off);
  const i = Math.floor(n),
    k = n - i;
  const t0 = b[i] ?? b[b.length - 1] + (i - b.length + 1) * (60 / B.bpm);
  const t1 = b[i + 1] ?? t0 + 60 / B.bpm;
  return at + t0 + (t1 - t0) * k - off;
}
// t 秒之後最近的拍點（過場的秒數）
export function snapBeat(track, t, off = 0, at = 0) {
  const B = BEATS[track];
  if (!B) return t;
  const x = t - at + off;
  const b = B.beats.find((v) => v >= x);
  return b == null ? t : at + b - off;
}
