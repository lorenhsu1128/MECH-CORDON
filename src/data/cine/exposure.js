// 一鏡的鍵：場景與鏡頭的 JSON 的雜湊（FNV-1a）
export function shotKey(S) {
  const s = JSON.stringify([S.set || null, S.cam || null]);
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
}
