// 這句台詞的 { e 表情, a 動作 }。ev＝通訊事件（data/story-comms.js），cue＝系統提示的 id
export function lineExpr(text, { ev, cue } = {}) {
  const s = LINE_EXPR[text];
  let e, a;
  if (s) [e, a] = s.split(' ');
  else if (cue) e = CUE_EXPR[cue] || (/^wave/.test(cue) ? 'focus' : 'neutral');
  else e = EVENT_EXPR[ev] || 'neutral';
  return { e, a: a || ACT_OF_EXPR[e] || null };
}
