//  特效自己的亂數（docs/vfx-design.md 第 7 期）：粒子、彈殼、碎片這些只有外觀的東西不取用遊戲的亂數
//  （core/math.js 的 RNG／Math.random），所以砲火特效的設定、特效的多寡不會改變 AI 與招式的亂數順序
//  （冒煙測試固定種子時結果一致；多人是房主權威，外觀各端各自算，本來就不需要一致）。
// ============================================================
let s = 0x2f6b1d3 >>> 0;
export function frand() {
  s = (s + 0x6d2b79f5) >>> 0;
  let t = s;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
export const frnd = (a, b) => a + frand() * (b - a);
