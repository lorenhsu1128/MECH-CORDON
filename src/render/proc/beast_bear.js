// 排煙管：槍鐵色的短管＋管口的火光
const stack = (x, y, z, h, r, mir) => [
  lathe(
    GUN,
    [x, y, z],
    [0, 1, -0.18],
    [
      [0, r * 1.15],
      [h * 0.2, r],
      [h, r],
      [h + 0.08, r * 1.12],
    ],
    8,
    mir,
  ),
  lathe(
    BURN,
    [x, y + h * 0.985, z - h * 0.177],
    [0, 1, -0.18],
    [
      [0, r * 0.8],
      [0.06, r * 0.75],
    ],
    8,
    mir,
  ),
];

