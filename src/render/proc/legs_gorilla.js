// 拳：c＝指節的位置；四指握起以指節撐地、拇指在內側（−x）；沒有爪
export function gorillaFist(c) {
  const out = [];
  [-0.6, -0.2, 0.2, 0.6].forEach((ox, i) => {
    const x = c[0] + ox;
    const dz = i === 0 || i === 3 ? -0.08 : 0;
    out.push(
      // 指節（正圓）
      cyl(JOINT, [x - 0.17, c[1], c[2] + dz], [x + 0.17, c[1], c[2] + dz], 0.3, 10),
      // 第一節：從指節往前下到地面
      box(MAIN, [x, 0.3, c[2] + dz + 0.28], [0.36, 0.5, 0.62], [28, 0, 0], 0.06),
      // 第二節：往回握
      box(SUB, [x, 0.14, c[2] + dz - 0.05], [0.32, 0.26, 0.6], null, 0.05),
    );
  });
  // 拇指
  out.push(
    cyl(JOINT, [c[0] - 0.95, c[1] + 0.05, c[2] - 0.35], [c[0] - 0.75, c[1] + 0.05, c[2] - 0.35], 0.24, 10),
    box(MAIN, [c[0] - 0.98, 0.3, c[2] - 0.05], [0.32, 0.4, 0.7], [20, 14, 0], 0.06),
  );
  return out;
}

