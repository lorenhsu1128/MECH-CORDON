const L = GORILLA_LEG;

export function gorillaFlUpper() {
  const { S, E } = L;
  const R = seg(S, E, [
    [-0.12, oct(0.8, 0.9, 0.9)],
    [0, oct(1.0, 1.15, 1.15)],
    [0.45, oct(0.95, 1.05, 1.1)],
    [1, oct(0.78, 0.85, 0.88)],
    [1.07, oct(0.55, 0.58, 0.58)],
  ]);
  const o = vadd(S, [0.35, 0.35, 0]);
  return [
    loft(JOINT, R),
    // 半球形的肩罩
    lathe(
      MAIN,
      o,
      [1, 0.35, 0],
      [
        [-0.2, 1.55],
        [0.35, 1.5],
        [0.8, 1.2],
        [1.1, 0.75],
        [1.25, 0.25],
      ],
      12,
    ),
    // 肩罩外圈的飾環與頂上的蓋
    lathe(
      ACC,
      o,
      [1, 0.35, 0],
      [
        [-0.28, 1.62],
        [-0.08, 1.62],
        [-0.04, 1.5],
      ],
      12,
    ),
    lathe(
      SUB,
      vadd(o, [1.18, 0.41, 0]),
      [1, 0.35, 0],
      [
        [0, 0.42],
        [0.12, 0.42],
        [0.17, 0.28],
      ],
      10,
    ),
    // 上臂外側與前面的甲
    panel(MAIN, R, 1.35, 2.9, 7, 10.5, { t: 0.18, ch: 0.08 }),
    ...piston(GUN, STEEL, vadd(S, [0.1, -0.6, -1.15]), vadd(E, [0, 0.5, -0.7]), 0.14),
    ...roundJoint(E, 0.75, 0.95),
  ];
}
