// 腳掌：c＝蹠骨前端；四趾往前、大腳趾往內張開
export function gorillaFoot(c) {
  const g = (pts) => pts.map(([a, b, d]) => [c[0] + a, b, c[2] + d]);
  const sym = (pts) =>
    g(
      pts.flatMap(([a, b, d]) =>
        a
          ? [
              [a, b, d],
              [-a, b, d],
            ]
          : [[a, b, d]],
      ),
    );
  const out = [
    ...roundJoint(c, 0.36, 0.72),
    hull(
      MAIN,
      sym([
        [0.75, 0.05, -0.7],
        [0.7, 0.55, -0.6],
        [0.85, 0.05, 0.5],
        [0.8, 0.5, 0.4],
        [0.45, 0.8, -0.1],
      ]),
    ),
    box(SUB, [c[0], 0.04, c[2] - 0.1], [1.6, 0.08, 1.3], null, 0.03),
    // 腳跟
    hull(
      SUB,
      sym([
        [0.55, 0.05, -0.7],
        [0.5, 0.5, -0.7],
        [0.4, 0.05, -1.25],
        [0.35, 0.4, -1.2],
      ]),
    ),
    // 大腳趾（往內）
    cyl(JOINT, [c[0] - 0.95, 0.3, c[2] - 0.1], [c[0] - 0.75, 0.3, c[2] - 0.1], 0.24, 10),
    box(MAIN, [c[0] - 1.15, 0.2, c[2] + 0.25], [0.36, 0.36, 0.9], [0, -32, 0], 0.07),
  ];
  [-0.5, -0.17, 0.17, 0.5].forEach((ox) =>
    out.push(box(MAIN, [c[0] + ox, 0.2, c[2] + 0.85], [0.28, 0.36, 0.8], [6, 0, 0], 0.07)),
  );
  return out;
}
