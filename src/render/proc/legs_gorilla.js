// 猩猩型機獸的四肢（原生建模，不經過縮放；左側 +x）。指節著地：前肢（手臂）比後肢長得多——肱骨與前臂一樣長、各約 2.75 m，
// 手背短、以指節撐地；後肢短而彎：股骨與脛骨各約 1.9 m，蹠行的腳板、大腳趾往內張開（能抓握）。
// 造型：半球形的大肩罩（外圈一道飾環）、粗壯的前臂與方正的護手、前臂外側的絞盤與鉤（抓住平台用）、握成拳的四指與拇指（沒有爪）、
