// 掌：c＝踝的位置；圓厚的掌、四趾、短爪
export function lionPaw(c) {
  const g = (pts) => pts.map(([a, b, d]) => [c[0] + a, b, c[2] + d]);
  const sym = (pts) =>
    g(
      pts.flatMap(([a, b, d]) =>
        a
          ? [
              [a, b, d],
              [-a, b, d],
            ]
          : [[a, b, d]],
      ),
    );
  const out = [
    ...roundJoint(c, 0.38, 0.55),
    hull(
      MAIN,
      sym([
        [0.6, 0.06, -0.5],
        [0.54, 0.7, -0.42],
        [0.7, 0.06, 0.55],
        [0.66, 0.7, 0.42],
        [0.42, 1.02, -0.08],
        [0.42, 0.94, 0.28],
      ]),
    ),
    box(SUB, [c[0], 0.04, c[2] + 0.03], [1.22, 0.08, 0.96], null, 0.03),
    hull(
      SUB,
      sym([
        [0.28, 0.42, -0.42],
        [0.2, 0.14, -0.8],
        [0, 0.64, -0.72],
        [0.22, 0.1, -0.42],
      ]),
    ),
  ];
  [-0.52, -0.175, 0.175, 0.52].forEach((ox, i) => {
    const zo = i === 0 || i === 3 ? -0.1 : 0;
    const t = (pts) =>
      g(
        pts.flatMap(([a, b, d]) =>
          a
            ? [
                [ox + a, b, zo + d],
                [ox - a, b, zo + d],
              ]
            : [[ox, b, zo + d]],
        ),
      );
    out.push(
      hull(
        MAIN,
        t([
          [0.15, 0.04, 0.42],
          [0.15, 0.6, 0.42],
          [0.145, 0.04, 1.18],
          [0.12, 0.42, 1.2],
          [0.145, 0.64, 0.78],
        ]),
      ),
      hull(
        STEEL,
        t([
          [0.065, 0.42, 1.15],
          [0.065, 0.14, 1.2],
          [0, 0.03, 1.56],
          [0, 0.28, 1.38],
        ]),
      ),
    );
  });
  return out;
}

