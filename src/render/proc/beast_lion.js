// 身體的截面：半寬 w、頂 yt、底 yb
const sec = (z, w, yt, yb, k = 1) => {
  const h = yt - yb;
  const c = (yt + yb) / 2;
  return bodyRing(
    z,
    [
      [0, yt],
      [0.45 * w, yt - 0.03 * h],
      [0.86 * w, yt - 0.2 * h],
      [w, yt - 0.45 * h],
      [0.94 * w, yt - 0.72 * h],
      [0.58 * w, yb + 0.07 * h],
      [0, yb],
    ].map(([x, y]) => [x * k, c + (y - c) * k]),
  );
};
// 背上的鰭（脊線）
