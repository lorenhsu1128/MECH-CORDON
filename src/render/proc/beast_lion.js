// ---------- 頸（含鬃甲）----------
function neck() {
  const R = tubeRings(
    [
      { p: [0, 5.45, 2.9], prof: oct(0.85, 0.95, 0.95) },
      { p: [0, 6.0, 3.55], prof: oct(0.9, 0.95, 0.95) },
      { p: [0, 6.55, 4.1], prof: oct(0.95, 1.0, 0.95) },
    ],
    [0, 1, 0],
  );
  const out = [
    loft(JOINT, R),
    panel(MAIN, R, 0, 2, 7.5, 9, { mir: true, t: 0.1 }),
    panel(SUB, R, 0, 2, 1, 2, { mir: true, t: 0.07 }),
    panel(SUB, R, 0, 2, 2, 3.5, { mir: true, t: 0.07 }),
  ];
  // 鬃甲：往後掃的刀形甲片，兩層交錯（後層長、前層短），繞著頸子上方約 250°
  const dn = vnorm([0, 0.6, 0.8]); // 頸子的軸
  const up = vnorm([0, 0.8, -0.6]);
  const C = J.mane;
  const maneA = [],
    maneB = [];
  const blade = (slot, th, back, len, hw, rise, rad = 0.7, lens = false) => {
    const a = (th * Math.PI) / 180;
    const r = vadd(vmul(up, Math.cos(a)), [Math.sin(a), 0, 0]); // 繞頸軸的徑向
    const rw = [Math.sin(a), Math.cos(a), 0];
    const D = vnorm(vadd(vmul(rw, rise), [0, 0, -1]));
    const Wd = vnorm([r[1] * D[2] - r[2] * D[1], r[2] * D[0] - r[0] * D[2], r[0] * D[1] - r[1] * D[0]]);
    const Nn = vnorm([D[1] * Wd[2] - D[2] * Wd[1], D[2] * Wd[0] - D[0] * Wd[2], D[0] * Wd[1] - D[1] * Wd[0]]);
    const o = Math.sign(Nn[0] * r[0] + Nn[1] * r[1] + Nn[2] * r[2]) || 1; // 往外的那一面
    const root = vadd(vadd(C, vmul(dn, -back)), vmul(r, rad));
    const at = (t, w, n) => vadd(vadd(root, vmul(D, t * len)), vadd(vmul(Wd, w), vmul(Nn, n * o)));
    const out2 = [];
    // 身上的武器（能量）：後層每片鬃甲的根部一面雷射鏡
    if (lens)
      out2.push(
        hull(LASER, [
          at(0.1, hw * 0.3, 0.1),
          at(0.1, -hw * 0.3, 0.1),
          at(0.31, hw * 0.3, 0.09),
          at(0.31, -hw * 0.3, 0.09),
          at(0.13, 0, 0.25),
          at(0.28, 0, 0.23),
        ]),
        hull(GLASS, [
          at(0.06, hw * 0.4, 0.08),
          at(0.06, -hw * 0.4, 0.08),
          at(0.35, hw * 0.4, 0.07),
          at(0.35, -hw * 0.4, 0.07),
          at(0.09, 0, 0.2),
          at(0.33, 0, 0.18),
        ]),
      );
    out2.push(
      hull(slot, [
        at(-0.08, hw * 0.75, -0.06),
        at(-0.08, -hw * 0.75, -0.06),
        at(-0.05, 0, 0.14),
        at(0.38, hw, -0.03),
        at(0.38, -hw, -0.03),
        at(0.38, 0, 0.13),
        at(0.4, hw * 0.8, -0.1),
        at(0.4, -hw * 0.8, -0.1),
        at(0, hw * 0.6, -0.16),
        at(0, -hw * 0.6, -0.16),
        at(1, hw * 0.55, -0.02),
        at(1, -hw * 0.55, -0.02),
        at(1.03, 0, 0.07),
        at(0.98, hw * 0.5, -0.1),
        at(0.98, -hw * 0.5, -0.1),
      ]),
    );
    return out2;
  };
  for (const th of [-114, -76, -38, 0, 38, 76, 114])
    maneA.push(...blade(MAIN, th, 0.5, 1.95 - Math.abs(th) * 0.004, 0.86, 0.75, 1.1, true));
  for (const th of [-133, -95, -57, -19, 19, 57, 95, 133])
    maneB.push(...blade(SUB, th, -0.02, 1.3 - Math.abs(th) * 0.002, 0.72, 1.35, 1.1));
  // 頸環
  out.push(
    lathe(
      ACC,
      vadd(C, vmul(dn, 0.1)),
      dn,
      [
        [-0.1, 1.08],
        [0.1, 1.08],
        [0.16, 0.96],
      ],
      14,
    ),
  );
  return { base: out, maneA, maneB };
}

