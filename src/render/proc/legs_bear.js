// 巨掌：c＝踝的位置；寬而圓、五趾、長爪；heel＝後腳的大腳跟墊（往後延伸到腳跟下）
export function bearPaw(c, heel = 0) {
  const g = (pts) => pts.map(([a, b, d]) => [c[0] + a, b, c[2] + d]);
  const sym = (pts) =>
    g(
      pts.flatMap(([a, b, d]) =>
        a
          ? [
              [a, b, d],
              [-a, b, d],
            ]
          : [[a, b, d]],
      ),
    );
  const out = [
    ...roundJoint(c, 0.5, 0.86),
    hull(
      MAIN,
      sym([
        [0.92, 0.07, -0.75],
        [0.86, 0.85, -0.6],
        [1.08, 0.07, 0.75],
        [1.02, 0.8, 0.6],
        [0.62, 1.2, -0.1],
        [0.62, 1.1, 0.4],
      ]),
    ),
    box(SUB, [c[0], 0.05, c[2]], [1.9, 0.1, 1.5], null, 0.04),
  ];
  if (heel)
    out.push(
      hull(
        SUB,
        sym([
          [0.8, 0.05, -0.7],
          [0.75, 0.6, -0.7],
          [0.6, 0.05, -0.7 - heel],
          [0.55, 0.5, -0.7 - heel],
          [0, 0.7, -0.7 - heel * 0.5],
        ]),
      ),
    );
  [-0.84, -0.42, 0, 0.42, 0.84].forEach((ox, i) => {
    const zo = [-0.22, -0.06, 0, -0.06, -0.22][i];
    const t = (pts) =>
      g(
        pts.flatMap(([a, b, d]) =>
          a
            ? [
                [ox + a, b, zo + d],
                [ox - a, b, zo + d],
              ]
            : [[ox, b, zo + d]],
        ),
      );
    out.push(
      hull(
        MAIN,
        t([
          [0.19, 0.05, 0.6],
          [0.19, 0.66, 0.6],
          [0.18, 0.05, 1.3],
          [0.15, 0.46, 1.34],
          [0.18, 0.7, 0.95],
        ]),
      ),
      // 長爪：略往下彎
      hull(
        STEEL,
        t([
          [0.08, 0.46, 1.28],
          [0.08, 0.18, 1.32],
          [0, 0.4, 1.75],
          [0, 0.03, 2.15],
          [0, 0.22, 1.9],
        ]),
      ),
    );
  });
  return out;
}

