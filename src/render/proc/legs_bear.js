const L = BEAR_LEG;
// 鉚釘：外側的小圓柱
const rivets = (o, pts, r = 0.09) =>
  pts.map(([y, z]) => cyl(ACC, [o[0], o[1] + y, o[2] + z], [o[0] + 0.07, o[1] + y, o[2] + z], r, 8));
// 爐火的散熱縫：深框裡三道火光
const vents = (o, n = 3, h = 0.8) => [
  box(GUN, [o[0], o[1], o[2]], [0.1, h + 0.2, n * 0.3 + 0.15], null, 0.03),
  ...Array.from({ length: n }, (_, k) =>
    box(BURN, [o[0] + 0.04, o[1], o[2] + (k - (n - 1) / 2) * 0.3], [0.08, h, 0.14]),
  ),
];

