// 熊型機獸的四肢（原生建模，不經過縮放；左側 +x）。蹠行：肱骨長、前臂約肱骨的 0.85、掌骨極短（整個掌貼地）；
// 股骨長、脛骨約股骨的 0.8、腳跟（跗關節）靠近地面，蹠骨從腳跟往前貼著地面——所以後腳是又長又平的腳板。後肢比前肢粗壯（使用者定案）。
// 造型：兩層巨石般的肩甲與髖甲（下緣有爐火的散熱縫、邊上一圈鉚釘）、前臂的護腕與三道箍、厚實的膝甲、巨掌與五支長爪、後腳的大腳跟墊。
