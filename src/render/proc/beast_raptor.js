// 造型取真實老鷹（大型的鵰）的特徵：厚實的胸與突出的龍骨、粗短的頸、平頂的頭與壓在眼上的眉骨（兇狠的眼神）、又大又深的鉤喙、後腦往後掃的冠羽、
// 往兩側平展的長翼（翼尖的初級飛羽像手指一樣分開）、包著羽褲的粗腿與大鉤爪、扇形的尾。
// 配合洋上都市的主題：翼尖的飛羽是鋼刃、兩翼下各一具推進器、背上一對主推進器。
// 大小照自然界的比例（大型的鵰站高約 1 m、翼展約 2.4 m → 站高約 5.8 m、翼展約 14 m；身體比玩家機甲矮，但翼展很寬）。
// 所有部位各自建模（翼與腿在 legs_raptor.js）；沒有用別隻的零件。模型的站姿＝翼平展，收翼靠關節轉。
