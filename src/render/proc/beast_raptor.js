// 尾：五片扇形的尾羽與蓋在根部的甲
function tail() {
  const o = T.tail;
  const out = [
    hullS(MAIN, [
      [0.6, 3.6, -1.5],
      [0, 3.72, -1.5],
      [0.7, 3.2, -1.5],
      [0, 3.0, -1.5],
      [0.85, 3.25, -2.5],
      [0, 3.42, -2.6],
      [0.8, 3.05, -2.5],
      [0, 2.95, -2.5],
    ]),
    cyl(JOINT, [-0.5, o[1], o[2]], [0.5, o[1], o[2]], 0.4, 14),
  ];
  [-0.5, -0.25, 0, 0.25, 0.5].forEach((a, k) => {
    const d = [Math.sin(a), -0.28, -Math.cos(a)];
    const len = 3.0 - Math.abs(a) * 0.8;
    const l = Math.hypot(...d);
    const n = d.map((v) => v / l);
    const s = [Math.cos(a), 0, Math.sin(a)];
    const dy = -Math.abs(k - 2) * 0.04;
    const P = (u, v, y) => [
      o[0] + n[0] * (0.5 + u * len) + s[0] * v,
      o[1] + n[1] * (0.5 + u * len) + y + dy,
      o[2] + n[2] * (0.5 + u * len) + s[2] * v,
    ];
    out.push(
      hull(SUB, [
        P(0, 0.3, 0.05),
        P(0, -0.3, 0.05),
        P(0, 0.3, -0.05),
        P(0, -0.3, -0.05),
        P(0.75, 0.42, 0.04),
        P(0.75, -0.42, 0.04),
        P(0.75, 0.42, -0.04),
        P(0.75, -0.42, -0.04),
        P(1, 0.3, 0),
        P(1, -0.3, 0),
      ]),
      // 尾羽末端的亮色帶
      hull(ACC, [
        P(0.8, 0.41, 0.06),
        P(0.8, -0.41, 0.06),
        P(0.8, 0.41, -0.06),
        P(0.8, -0.41, -0.06),
        P(1.01, 0.3, 0.02),
        P(1.01, -0.3, 0.02),
      ]),
    );
  });
  return out;
}

// ---------- 外掛武器一（爆發）：翼下的空對地導彈（左；右＝鏡像）----------
// 上臂下面兩道掛架，各掛一枚看得到全身的導彈：紅色的尖頭、細長的彈體、十字尾翼、噴口
function missiles() {
  const out = [];
  for (const [x, zc] of [
    [1.85, 0.55],
    [2.7, 0.42],
  ]) {
    const y = 3.5;
    out.push(
      // 掛架
      hull(SUB, [
        [x - 0.07, y + 0.55, zc + 0.5],
        [x + 0.07, y + 0.55, zc + 0.5],
        [x - 0.07, y + 0.55, zc - 0.5],
        [x + 0.07, y + 0.55, zc - 0.5],
        [x - 0.06, y + 0.17, zc + 0.75],
        [x + 0.06, y + 0.17, zc + 0.75],
        [x - 0.06, y + 0.17, zc - 0.6],
        [x + 0.06, y + 0.17, zc - 0.6],
      ]),
      box(GUN, [x, y + 0.19, zc + 0.05], [0.2, 0.07, 1.2], null, 0.02),
      // 彈體
      lathe(
        MAIN,
        [x, y, zc - 1.0],
        [0, 0, 1],
        [
          [0, 0.13],
          [0.08, 0.17],
          [1.65, 0.17],
          [1.72, 0.15],
        ],
        10,
      ),
      lathe(
        WAR,
        [x, y, zc + 0.72],
        [0, 0, 1],
        [
          [0, 0.15],
          [0.25, 0.13],
          [0.5, 0.05],
          [0.56, 0.01],
        ],
        10,
      ),
      cyl(ACC, [x, y, zc + 0.3], [x, y, zc + 0.4], 0.18, 10),
      cyl(GUN, [x, y, zc - 1.1], [x, y, zc - 1.0], 0.11, 8),
      // 十字尾翼
      hull(SUB, [
        [x - 0.4, y, zc - 1.0],
        [x + 0.4, y, zc - 1.0],
        [x - 0.17, y, zc - 0.5],
        [x + 0.17, y, zc - 0.5],
        [x, y + 0.02, zc - 0.8],
        [x, y - 0.02, zc - 0.8],
      ]),
      hull(SUB, [
        [x, y - 0.4, zc - 1.0],
        [x, y + 0.36, zc - 1.0],
        [x, y - 0.17, zc - 0.5],
        [x, y + 0.17, zc - 0.5],
        [x + 0.02, y, zc - 0.8],
        [x - 0.02, y, zc - 0.8],
      ]),
    );
  }
  return out;
}

// ---------- 外掛武器二（爆發）：腹下的集束炸彈艙 ----------
// 兩腿後面、貼著腹部的流線艙：艙底 2×3 個半露的圓頭子炸彈、兩側的艙門、前端的整流罩
const BAY = [0, 2.35, -0.95];
function bombBay() {
  const [, y, z] = BAY;
  const out = [
    hullS(MAIN, [
      [0.0, y + 0.1, z + 0.95],
      [0.42, y + 0.1, z + 0.7],
      [0.6, y + 0.1, z - 0.9],
      [0.4, y + 0.1, z - 1.25],
      [0.0, y - 0.3, z + 0.8],
      [0.36, y - 0.42, z + 0.55],
      [0.5, y - 0.48, z - 0.8],
      [0.34, y - 0.34, z - 1.15],
      [0.0, y - 0.52, z - 0.2],
    ]),
    box(ACC, [0.52, y - 0.14, z - 0.2], [0.03, 0.12, 1.2], null, 0, true),
    box(SUB, [0.5, y - 0.3, z - 0.2], [0.06, 0.2, 1.5], [0, 0, 10], 0.02, true),
    // 後端的排氣口
    box(GUN, [0, y - 0.15, z - 1.22], [0.5, 0.26, 0.1], null, 0.03),
  ];
  for (const x of [-0.2, 0.2])
    for (const dz of [0.35, -0.15, -0.65]) {
      out.push(cyl(GUN, [x, y - 0.5, z + dz], [x, y - 0.56, z + dz], 0.17, 10));
      out.push(
        lathe(
          WAR,
          [x, y - 0.54, z + dz],
          [0, -1, 0],
          [
            [0, 0.13],
            [0.07, 0.11],
            [0.12, 0.04],
          ],
          10,
        ),
      );
    }
  return out;
}

let DEF = null;
export function raptorDef() {
  if (DEF) return DEF;
  const { add, pair, done } = assembler();
  add('chest', null, T.chest, chest());
  add('neck', 'chest', T.neck, neck());
  add('head', 'neck', T.head, head());
  add('jaw', 'head', T.jaw, jaw());
  add('tail', 'chest', T.tail, tail());
  // 翼：上臂 → 前臂 → 手
  pair('wl_arm', 'wr_arm', 'chest', 'chest', RAPTOR_WING.S, [...raptorWingArm(), ...missiles()]);
  add('bay', 'chest', BAY, bombBay());
  pair('wl_fore', 'wr_fore', 'wl_arm', 'wr_arm', RAPTOR_WING.E, raptorWingFore());
  pair('wl_hand', 'wr_hand', 'wl_fore', 'wr_fore', RAPTOR_WING.W, raptorWingHand());
  // 腿：脛 → 跗蹠 → 腳掌（後趾）→ 前三趾
  pair('l_thigh', 'r_thigh', 'chest', 'chest', RAPTOR_LEG.H, raptorThigh());
  pair('l_tarsus', 'r_tarsus', 'l_thigh', 'r_thigh', RAPTOR_LEG.A, raptorTarsus());
  pair('l_foot', 'r_foot', 'l_tarsus', 'r_tarsus', RAPTOR_LEG.F, raptorFoot());
  pair('l_toes', 'r_toes', 'l_foot', 'r_foot', RAPTOR_LEG.T, raptorToes());
  DEF = done(RAPTOR_COLS, 'raptor');
  return DEF;
}
