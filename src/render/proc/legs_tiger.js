// 尾巴的節：細長、越後面越細；單數節中段一圈條紋
export function tigerTailSeg(k) {
  const a = L.tail[k],
    b = L.tail[k + 1];
  const r0 = 0.3 - k * 0.036,
    r1 = r0 - 0.036;
  const R = seg(
    a,
    b,
    [
      [0.06, oct(r0 * 0.9, r0, r0)],
      [0.94, oct(r1 * 0.9, r1, r1)],
    ],
    [0, 1, 0],
  );
  const out = [
    loft(JOINT, R),
    panel(MAIN, R, 0, 1, 6, 9, { t: 0.06, gap: 0.03, ch: 0.03 }),
    ball(SUB, b, r1 * 1.25, 10),
  ];
  if (k % 2 === 0) out.push(panel(ACC, R, 0.4, 0.6, 0, 8, { t: 0.08, gap: 0.0, ch: 0.02 }));
  return out;
}
