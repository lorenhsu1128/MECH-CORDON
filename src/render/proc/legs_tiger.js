// 掌：窄而長、四趾、長鉤爪，內側（−x）一支懸爪
export function tigerPaw(c) {
  const g = (pts) => pts.map(([a, b, d]) => [c[0] + a, b, c[2] + d]);
  const sym = (pts) =>
    g(
      pts.flatMap(([a, b, d]) =>
        a
          ? [
              [a, b, d],
              [-a, b, d],
            ]
          : [[a, b, d]],
      ),
    );
  const out = [
    ...roundJoint(c, 0.34, 0.46),
    hull(
      MAIN,
      sym([
        [0.46, 0.05, -0.5],
        [0.42, 0.6, -0.4],
        [0.54, 0.05, 0.6],
        [0.5, 0.56, 0.5],
        [0.3, 0.9, -0.05],
        [0.3, 0.82, 0.3],
      ]),
    ),
    box(SUB, [c[0], 0.035, c[2] + 0.05], [0.96, 0.07, 1.0], null, 0.03),
    // 懸爪
    hull(
      STEEL,
      g([
        [-0.5, 0.5, -0.2],
        [-0.5, 0.3, -0.25],
        [-0.72, 0.12, 0.1],
        [-0.56, 0.38, 0.0],
      ]),
    ),
  ];
  [-0.39, -0.13, 0.13, 0.39].forEach((ox, i) => {
    const zo = i === 0 || i === 3 ? -0.12 : 0;
    const t = (pts) =>
      g(
        pts.flatMap(([a, b, d]) =>
          a
            ? [
                [ox + a, b, zo + d],
                [ox - a, b, zo + d],
              ]
            : [[ox, b, zo + d]],
        ),
      );
    out.push(
      hull(
        MAIN,
        t([
          [0.115, 0.04, 0.45],
          [0.115, 0.5, 0.45],
          [0.105, 0.04, 1.3],
          [0.09, 0.36, 1.32],
          [0.11, 0.56, 0.85],
        ]),
      ),
      // 長鉤爪：先往前上、再往下鉤
      hull(
        STEEL,
        t([
          [0.05, 0.4, 1.26],
          [0.05, 0.16, 1.3],
          [0, 0.5, 1.62],
          [0, 0.02, 1.95],
          [0, 0.22, 1.7],
        ]),
      ),
    );
  });
  return out;
}

